/**
 * Access a translation string by section and key with fallback to English.
 *
 * @param {string} lang - 'en' | 'hi'
 * @param {string} section - category name (e.g. 'nav', 'buttons', 'common')
 * @param {string} key - key within the category (e.g. 'today', 'save')
 * @returns {string} Translated string or fallback
 */
export function t(lang = "en", section, key) {
  const selectedLang = lang === "hi" ? "hi" : "en";
  const dict = translations[selectedLang] ?? translations.en;
  const sectionObj = dict[section] ?? translations.en[section];

  if (!sectionObj) {
    return key;
  }

  return sectionObj[key] ?? translations.en[section]?.[key] ?? key;
}

/**
 * Access a translation string by dot path (e.g. 'nav.today', 'buttons.save').
 *
 * @param {string} lang - 'en' | 'hi'
 * @param {string} dotPath - path separated by dots
 * @param {string} [fallback] - optional custom fallback
 * @returns {string} Translated string or fallback
 */
export function getTranslation(lang = "en", dotPath, fallback = "") {
  if (!dotPath || typeof dotPath !== "string") {
    return fallback;
  }

  const selectedLang = lang === "hi" ? "hi" : "en";
  const parts = dotPath.split(".");

  function resolvePath(dictionary) {
    return parts.reduce(
      (current, part) =>
        current && typeof current === "object" ? current[part] : undefined,
      dictionary,
    );
  }

  const translated = resolvePath(translations[selectedLang]);
  if (typeof translated === "string") return translated;

  const englishFallback = resolvePath(translations.en);
  if (typeof englishFallback === "string") return englishFallback;

  return fallback || dotPath;
}
